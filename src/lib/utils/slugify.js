// "Sri Lanka Women" -> "sri-lanka-women". Used to build stable IDs when a
// provider gives us a name but no ID.
export function slugify(text) {
  return String(text)
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
